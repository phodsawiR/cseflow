def _build_moc(output_dir: str, topics: dict):
    lines = ["# 🗺️ Map of Content — Ward Medicine\n",
             "*Auto-generated by CaseFlow Vault Builder*\n"]
    for topic_type, topic_list in topics.items():
        lines.append(f"\n## {topic_type.capitalize()}\n")
        for topic in topic_list:
            lines.append(f"- [[{topic}]]")
    lines += ["\n\n---", "*Generated by CaseFlow Vault Builder*"]
    with open(os.path.join(output_dir, "MOC.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"  ✅ MOC updated")


