# ─── Parallel helper ─────────────────────────────────────────────────────────

def _parallel(calls: list[tuple]) -> list[str]:
    """Run agent calls concurrently. calls = [(name, prompt, system), ...]"""
    with concurrent.futures.ThreadPoolExecutor(max_workers=len(calls)) as ex:
        futures = [ex.submit(call_agent, name, prompt, system) for name, prompt, system in calls]
        return [f.result() for f in futures]


def _query_knowledge(topic: str, focus: str) -> tuple[str, str]:
    """
    ดึงข้อมูลจาก 2 แหล่ง:
    1. NotebookLM (KB) — primary, ใช้ความรู้ที่เราเพิ่มเองไว้
    2. researcher (Gemini + grounding) — fallback ถ้า KB ยังไม่มีเนื้อหา

    Returns: (kb_result, research_result) — อาจเป็นว่างถ้าหาไม่เจอ
    """
    kb_result = ""
    if _KB_AVAILABLE:
        try:
            result = query_notebook("medicine", f"สรุปข้อมูลเรื่อง {topic}: {focus}")
            if result and not any(m in result for m in _KB_MISS_MARKERS):
                kb_result = result
                print(f"  ✅ KB hit — NotebookLM")
            else:
                print(f"  ℹ️  KB miss — falling back to researcher")
        except Exception as e:
            print(f"  ⚠️  KB error: {e} — falling back to researcher")

    research_result = ""
    if not kb_result:
        try:
            result = call_agent(
                "researcher",
                system=load_prompt("researcher") or "",
                prompt=(
                    f"ค้นหาข้อมูล {focus} เรื่อง {topic} สำหรับ ward medicine ปี 4\n"
                    f"เน้น: current guidelines, key evidence, สิ่งที่ต้องรู้บน ward\n"
                    f"สรุปเป็นข้อๆ ภาษาอังกฤษ/ไทยผสม ไม่เกิน 800 คำ"
                ),
            )
            research_result = "" if result.startswith("[ERROR") else result
        except Exception as e:
            print(f"  ⚠️  researcher failed: {e}")

    return kb_result, research_result


def _best_knowledge(kb: str, research: str) -> str:
    """เลือกแหล่งที่ดีที่สุด — KB ก่อน ถ้าว่างใช้ research"""
    return kb or research or ""


